def tiff_block(ifd0: dict, exif: dict, gps: bool = True) -> bytes:
    """Little-endian TIFF with IFD0 (ASCII tags), an EXIF IFD and an optional GPS IFD."""
    entries0 = sorted(ifd0.items())
    exif_entries = sorted(exif.items())
    n0 = len(entries0) + 1 + (1 if gps else 0)
    ifd0_size = 2 + 12 * n0 + 4
    exif_offset = 8 + ifd0_size
    exif_size = 2 + 12 * len(exif_entries) + 4
    gps_offset = exif_offset + exif_size
    gps_size = (2 + 12 + 4) if gps else 0
    data_offset = gps_offset + gps_size
    data = b''

    def entry(tag, text):
        nonlocal data
        raw = text.encode('ascii') + b'\x00'
        if len(raw) <= 4:
            return struct.pack('<HHI', tag, 2, len(raw)) + raw.ljust(4, b'\x00')
        offset = data_offset + len(data)
        data += raw + (b'\x00' if len(raw) % 2 else b'')
        return struct.pack('<HHII', tag, 2, len(raw), offset)

    ifd0_bytes = struct.pack('<H', n0) + b''.join(entry(t, v) for t, v in entries0)
    ifd0_bytes += struct.pack('<HHII', 0x8769, 4, 1, exif_offset)
    if gps:
        ifd0_bytes += struct.pack('<HHII', 0x8825, 4, 1, gps_offset)
    ifd0_bytes += struct.pack('<I', 0)
    exif_bytes = struct.pack('<H', len(exif_entries)) + b''.join(entry(t, v) for t, v in exif_entries) + struct.pack('<I', 0)
    gps_bytes = (struct.pack('<H', 1) + struct.pack('<HHI', 0x0000, 1, 4) + bytes([2, 3, 0, 0]) + struct.pack('<I', 0)) if gps else b''
    return b'II*\x00' + struct.pack('<I', 8) + ifd0_bytes + exif_bytes + gps_bytes + data


def jpeg(tiff: bytes | None, payload: bytes = b'synthetic-scan-data') -> bytes:
    """SOI [+ APP1 Exif] + a comment segment + EOI; not a decodable picture."""
    out = b'\xff\xd8'
    if tiff is not None:
        segment = b'Exif\x00\x00' + tiff
        out += b'\xff\xe1' + struct.pack('>H', len(segment) + 2) + segment
    comment = b'AGEDS synthetic ' + payload
    out += b'\xff\xfe' + struct.pack('>H', len(comment) + 2) + comment
    return out + b'\xff\xd9'


